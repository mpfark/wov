// Composition only: no SQL execution, registration or installation.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root='docs/operations/';
const inputs=['progression-001G-C2-P2-B-cutover-containment.sql',
  'progression-001G-C2-P2-C-runtime-exclusions.sql',
  'progression-001G-C2-integrated-family-guard.sql',
  'progression-001G-C2-P2-C-lifecycle-cutover.sql','progression-001G-C2-integrated-enable.sql'];
const output='-- B: coordinated C2 cutover, NOT INSTALLED. Standard Drizzle ONE transaction.\n'
  +'-- Generated by scripts/prepare-c2-integrated-cutover.mjs; do not install components separately.\n'
  +inputs.map(name=>{
    const bytes=readFileSync(root+name); const hash=createHash('sha256').update(bytes).digest('hex');
    return `\n-- Component: ${name}; SHA-256 ${hash}\n`+bytes.toString('utf8');
  }).join('\n');
const path=root+'progression-001G-C2-integrated-cutover.sql';
if(process.argv.includes('--check')) {
  if(readFileSync(path,'utf8')!==output) throw Error('Cutover composition differs from reviewed inputs');
} else writeFileSync(path,output);
console.log(`${path}: ${createHash('sha256').update(output).digest('hex')}`);
