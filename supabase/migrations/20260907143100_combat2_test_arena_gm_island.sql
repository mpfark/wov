-- Move only the permanent Combat2 Test Arena plus to the eastern GM island.
DO $$
DECLARE moved integer;
BEGIN
  IF (SELECT count(*) FROM public.combat2_test_arena_node
      WHERE arena_id='ffff5000-0000-4000-8000-000000000002'
        AND node_id IN ('ffff5010-0000-4000-8000-000000000001','ffff5011-0000-4000-8000-000000000001',
          'ffff5012-0000-4000-8000-000000000001','ffff5013-0000-4000-8000-000000000001','ffff5014-0000-4000-8000-000000000001')) <> 5 THEN
    RAISE EXCEPTION 'Combat2 Test Arena registry identity mismatch';
  END IF;
  IF EXISTS (SELECT 1 FROM public.nodes WHERE (x,y) IN ((37,0),(37,-1),(38,0),(37,1),(36,0))
      AND id NOT IN ('ffff5010-0000-4000-8000-000000000001','ffff5011-0000-4000-8000-000000000001',
        'ffff5012-0000-4000-8000-000000000001','ffff5013-0000-4000-8000-000000000001','ffff5014-0000-4000-8000-000000000001')) THEN
    RAISE EXCEPTION 'Combat2 GM-island coordinate collision';
  END IF;
  UPDATE public.nodes SET
    x=CASE id WHEN 'ffff5010-0000-4000-8000-000000000001' THEN 37 WHEN 'ffff5011-0000-4000-8000-000000000001' THEN 37
      WHEN 'ffff5012-0000-4000-8000-000000000001' THEN 38 WHEN 'ffff5013-0000-4000-8000-000000000001' THEN 37
      WHEN 'ffff5014-0000-4000-8000-000000000001' THEN 36 END,
    y=CASE id WHEN 'ffff5010-0000-4000-8000-000000000001' THEN 0 WHEN 'ffff5011-0000-4000-8000-000000000001' THEN -1
      WHEN 'ffff5012-0000-4000-8000-000000000001' THEN 0 WHEN 'ffff5013-0000-4000-8000-000000000001' THEN 1
      WHEN 'ffff5014-0000-4000-8000-000000000001' THEN 0 END
  WHERE id IN ('ffff5010-0000-4000-8000-000000000001','ffff5011-0000-4000-8000-000000000001',
    'ffff5012-0000-4000-8000-000000000001','ffff5013-0000-4000-8000-000000000001','ffff5014-0000-4000-8000-000000000001');
  GET DIAGNOSTICS moved=ROW_COUNT;
  IF moved<>5 THEN RAISE EXCEPTION 'expected five Combat2 Test Arena nodes, updated %',moved; END IF;
END $$;
